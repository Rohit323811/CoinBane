/** A section band: the number, the title, and a rule under both. */
function sectionHeading(writer: Writer, index: number, title: string): void {
  writer.ensure(64);
  writer.y -= 6;
  writer.page.drawText(pdfSafe(`SECTION ${index}`), {
    x: MARGIN,
    y: writer.y,
    size: 8,
    font: writer.fonts.bold,
    color: ACCENT,
  });
  writer.y -= 18;
  writer.page.drawText(pdfSafe(title), {
    x: MARGIN,
    y: writer.y,
    size: 15,
    font: writer.fonts.bold,
    color: INK,
  });
  writer.y -= 10;
  writer.page.drawLine({
    start: { x: MARGIN, y: writer.y },
    end: { x: PAGE.width - MARGIN, y: writer.y },
    thickness: 1,
    color: LINE,
  });
  writer.y -= 20;
}

function drawCover(doc: PDFDocument, fonts: Fonts, pack: DisputeProofPack): void {
  const page = doc.getPages()[0];
  const { regular, bold, italic } = fonts;

  page.drawText("CoinBane", { x: MARGIN, y: PAGE.height - 70, size: 20, font: bold, color: INK });
  page.drawText(pdfSafe("Command every coin."), {
    x: MARGIN,
    y: PAGE.height - 86,
    size: 9.5,
    font: regular,
    color: MUTED,
  });
  rightAlign(
    page,
    `Generated ${formatDay(pack.generatedAt)}`,
    PAGE.width - MARGIN,
    PAGE.height - 70,
    9.5,
    regular,
    MUTED,
  );

  page.drawLine({
    start: { x: MARGIN, y: PAGE.height - 108 },
    end: { x: PAGE.width - MARGIN, y: PAGE.height - 108 },
    thickness: 1,
    color: LINE,
  });

  /* Title block. */
  page.drawText(pdfSafe("DISPUTE PROOF PACK"), {
    x: PAGE.width / 2 - bold.widthOfTextAtSize("DISPUTE PROOF PACK", 30) / 2,
    y: PAGE.height - 190,
    size: 30,
    font: bold,
    color: INK,
  });
  page.drawLine({
    start: { x: PAGE.width / 2 - 90, y: PAGE.height - 208 },
    end: { x: PAGE.width / 2 + 90, y: PAGE.height - 208 },
    thickness: 2,
    color: ACCENT,
  });

  centerAlign(
    page,
    pack.client,
    PAGE.height - 240,
    16,
    bold,
    INK,
  );
  centerAlign(
    page,
    `${formatPdfMoney(pack.amount, pack.currency)} in dispute`,
    PAGE.height - 262,
    12,
    regular,
    MUTED,
  );

  /* The facts of the case, two columns. */
  const detailTop = PAGE.height - 320;
  const left = [
    ["Client", pack.client],
    ["Dispute ID", pack.dispute?.id ?? "None on file"],
    ["Dispute reason", pack.dispute?.reason ?? "No dispute recorded"],
    ["Status", pack.dispute?.status ?? "—"],
    ["Opened", pack.dispute?.openedAt ? formatDay(pack.dispute.openedAt) : "—"],
    [
      "Response deadline",
      pack.dispute?.respondBy ? formatDay(pack.dispute.respondBy) : "—",
    ],
  ];
  const right = [
    ["Invoice number", pack.invoice?.number ?? "—"],
    ["Invoice status", pack.invoice?.status ?? "—"],
    ["Invoice total", pack.invoice ? formatPdfMoney(pack.invoice.total, pack.invoice.currency) : "—"],
    ["Issued", pack.invoice?.issued ? formatDay(pack.invoice.issued) : "—"],
    ["Due", pack.invoice?.due ? formatDay(pack.invoice.due) : "On receipt"],
    ["Payments applied", formatPdfMoney(pack.amount - pack.outstanding, pack.currency)],
  ];
  const rightColumn = MARGIN + 265;

  for (const [index, entry] of left.entries()) {
    const y = detailTop - index * 34;
    label(page, bold, entry[0], MARGIN, y);
    page.drawText(pdfSafe(fit(bold, entry[1], 10.5, 240)), {
      x: MARGIN,
      y: y - 15,
      size: 10.5,
      font: bold,
      color: INK,
    });
  }
  for (const [index, entry] of right.entries()) {
    const y = detailTop - index * 34;
    label(page, bold, entry[0], rightColumn, y);
    page.drawText(pdfSafe(fit(bold, entry[1], 10.5, 240)), {
      x: rightColumn,
      y: y - 15,
      size: 10.5,
      font: bold,
      color: INK,
    });
  }

  /* The one paragraph the pack is required to open with. */
  const summary =
    "This document contains all evidence supporting the freelancer's position in the dispute referenced above.";
  const summaryTop = detailTop - left.length * 34 - 6;
  for (const [index, line] of wrapText(regular, summary, 11, PAGE.width - MARGIN * 2 - 40).entries()) {
    centerAlign(page, line, summaryTop - index * 16, 11, regular, INK);
  }

  /*
   * Provenance, stated plainly.
   *
   * A document that reads as evidence must say where its dispute record came
   * from. PayPal's sandbox holds no disputes at all, so a pack built in a demo
   * deployment is assembled from the simulated ledger or prepared ahead of a
   * dispute — and the reader has to be able to tell which.
   */
  const provenance =
    pack.dispute?.source === "simulated"
      ? "Dispute record: simulated ledger fixture. PayPal holds no dispute with this id — this is a prepared draft, not a PayPal case file."
      : pack.dispute
        ? "Dispute record: PayPal sandbox, read directly from the dispute."
        : "No PayPal dispute is on file for this invoice. This pack was prepared ahead of a dispute.";
  const provenanceTop = summaryTop - 40;
  for (const [index, line] of wrapText(
    italic,
    provenance,
    9.5,
    PAGE.width - MARGIN * 2 - 80,
  ).entries()) {
    centerAlign(page, line, provenanceTop - index * 14, 9.5, italic, WARNING);
  }

  /* Wordmark and tagline, at the foot of the cover. */
  centerAlign(page, "CoinBane", MARGIN + 46, 14, bold, INK);
  centerAlign(page, "Command every coin.", MARGIN + 30, 9.5, regular, MUTED);

  /* Continue on a fresh page for section 1. */
  doc.addPage([PAGE.width, PAGE.height]);
}

function drawTimelineSection(writer: Writer, pack: DisputeProofPack): void {
  sectionHeading(writer, 2, "Communication timeline");
  if (pack.timeline.length === 0) {
    drawParagraph(writer, "No dated events were recorded for this dispute.", {
      color: MUTED,
    });
    return;
  }

  const eventX = MARGIN + 96;
  const eventWidth = PAGE.width - MARGIN - eventX;

  for (const entry of pack.timeline) {
    writer.ensure(34);
    writer.page.drawText(pdfSafe(formatDay(entry.date)), {
      x: MARGIN,
      y: writer.y,
      size: 9,
      font: writer.fonts.bold,
      color: INK,
    });

    const lines = wrapText(writer.fonts.regular, entry.event, 9.5, eventWidth);
    for (const [index, line] of lines.entries()) {
      if (index > 0) writer.ensure(13);
      writer.page.drawText(line, {
        x: eventX,
        y: writer.y - index * 13,
        size: 9.5,
        font: writer.fonts.regular,
        color: INK,
      });
    }
    writer.y -= lines.length * 13;

    writer.ensure(12);
    writer.page.drawText(
      pdfSafe(`${entry.actor} \u00b7 source: ${entry.kind}`),
      { x: eventX, y: writer.y, size: 8, font: writer.fonts.regular, color: MUTED },
    );
    writer.y -= 18;
  }

  /*
   * A trimmed timeline has to say so. A reader comparing it against PayPal's
   * own thread must not read the gap as a client who went quiet.
   */
  if (pack.timelineOmitted) {
    writer.ensure(20);
    drawParagraph(
      writer,
      `${pack.timelineOmitted} further events are omitted from this timeline to keep the pack readable. The records behind them are on file and can be produced in full on request.`,
      { color: MUTED },
    );
  }
}

function drawPaymentsSection(writer: Writer, pack: DisputeProofPack, fonts: Fonts): void {
  sectionHeading(writer, 3, "Payment history");

  if (pack.payments.length === 0) {
    drawParagraph(
      writer,
      `No payments have been received against this invoice. The full ${formatPdfMoney(pack.amount, pack.currency)} is outstanding.`,
      { color: INK },
    );
  } else {
    const columns = {
      date: MARGIN,
      reference: MARGIN + 110,
      amountRight: MARGIN + 400,
      balanceRight: PAGE.width - MARGIN,
    };
    writer.ensure(26);
    writer.page.drawRectangle({
      x: MARGIN,
      y: writer.y - 6,
      width: PAGE.width - MARGIN * 2,
      height: 20,
      color: PANEL,
    });
    label(writer.page, fonts.bold, "Date", columns.date + 6, writer.y + 1);
    label(writer.page, fonts.bold, "Reference", columns.reference, writer.y + 1);
    rightAlign(writer.page, "Amount", columns.amountRight, writer.y + 1, 7.5, fonts.bold, MUTED);
    rightAlign(writer.page, "Balance", columns.balanceRight, writer.y + 1, 7.5, fonts.bold, MUTED);
    writer.y -= 26;

    for (const payment of pack.payments) {
      writer.ensure(22);
      writer.page.drawText(pdfSafe(formatDay(payment.date)), {
        x: columns.date + 6,
        y: writer.y,
        size: 9.5,
        font: fonts.regular,
        color: INK,
      });
      writer.page.drawText(pdfSafe(fit(fonts.regular, payment.reference, 9.5, 200)), {
        x: columns.reference,
        y: writer.y,
        size: 9.5,
        font: fonts.regular,
        color: MUTED,
      });
      rightAlign(
        writer.page,
        formatPdfMoney(payment.amount, payment.currency),
        columns.amountRight,
        writer.y,
        9.5,
        fonts.regular,
        INK,
      );
      rightAlign(
        writer.page,
        formatPdfMoney(payment.balance, payment.currency),
        columns.balanceRight,
        writer.y,
        9.5,
        fonts.regular,
        MUTED,
      );
      writer.y -= 8;
      writer.page.drawLine({
        start: { x: MARGIN, y: writer.y },
        end: { x: PAGE.width - MARGIN, y: writer.y },
        thickness: 0.5,
        color: LINE,
      });
      writer.y -= 14;
    }

    /*
     * The table is trimmed on long histories, never the arithmetic: this line
     * is the balance after every payment recorded, not just the rows above it.
     */
    if (pack.paymentsOmitted) {
      drawParagraph(
        writer,
        `${pack.paymentsOmitted} earlier payments are omitted from this table. The outstanding balance below accounts for all of them.`,
        { size: 9, color: MUTED },
      );
      writer.y -= 2;
    }

    writer.ensure(24);
    rightAlign(writer.page, "OUTSTANDING", columns.amountRight, writer.y, 9, fonts.bold, MUTED);
    rightAlign(
      writer.page,
      formatPdfMoney(pack.outstanding, pack.currency),
      columns.balanceRight,
      writer.y,
      11.5,
      fonts.bold,
      INK,
    );
    writer.y -= 26;
  }

  if (pack.clientPayments.length > 0) {
    writer.ensure(40);
    drawParagraph(
      writer,
      `Other payments from ${pack.client} on record, for context:`,
      { size: 9, color: MUTED },
    );
    writer.y -= 2;
    for (const payment of pack.clientPayments) {
      writer.ensure(14);
      writer.page.drawText(
        pdfSafe(
          `${formatDay(payment.date)}  \u00b7  ${formatPdfMoney(payment.amount, pack.currency)}${payment.refunded ? " (refunded)" : ""}  \u00b7  ${payment.reference}`,
        ),
        { x: MARGIN, y: writer.y, size: 9, font: writer.fonts.regular, color: INK },
      );
      writer.y -= 14;
    }
    writer.y -= 8;
  }
}

function drawPositionSection(writer: Writer, pack: DisputeProofPack): void {
  sectionHeading(writer, 4, "The freelancer's position");
  writer.ensure(40);
  drawParagraph(writer, pack.position.text, { size: 10.5, lineHeight: 15 });
  writer.y -= 8;
  drawParagraph(
    writer,
    pack.position.source === "model"
      ? "Drafted by CoinBane from the records in this pack. Read it before you file: you are the one signing it."
      : "Drafted from the records in this pack without the model (no model key configured). Read it before you file: you are the one signing it.",
    { size: 8.5, color: MUTED },
  );
  writer.y -= 6;
}

function drawEvidenceSection(writer: Writer, pack: DisputeProofPack): void {
  sectionHeading(writer, 5, "Supporting evidence to attach");

  writer.ensure(30);
  drawParagraph(
    writer,
    "These items are listed rather than attached: only you hold them. Attach each one to the PayPal dispute response.",
    { size: 9.5, color: MUTED },
  );
  writer.y -= 10;

  for (const item of pack.evidence) {
    writer.ensure(38);
    drawParagraph(writer, `[ATTACH: ${item.description}]`, {
      size: 10,
      font: writer.fonts.bold,
      lineHeight: 14,
    });
    drawParagraph(writer, item.note, { size: 8.5, color: MUTED, lineHeight: 12 });
    writer.y -= 8;
  }

  if (pack.dispute?.respondBy) {
    writer.ensure(30);
    drawParagraph(
      writer,
      `File the response and these attachments with PayPal before ${formatDay(pack.dispute.respondBy)}.`,
      { size: 10, font: writer.fonts.bold, color: INK },
    );
  }
}

/**
 * The dispute proof pack: cover page, the invoice it concerns, and the evidence
 * around it.
 *
 * Where the pack has no invoice — a dispute can name an invoice PayPal will not
 * return — section 1 says so and the rest of the pack still stands.
 */
export async function generateDisputePackPdf(pack: DisputeProofPack): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const fonts = await embedFonts(doc);

  doc.setTitle(
    pdfSafe(`Dispute proof pack - ${pack.client} - ${formatPdfMoney(pack.amount, pack.currency)}`),
  );
  doc.setAuthor(pdfSafe(pack.invoice?.invoicer.business ?? pack.invoice?.invoicer.name ?? "CoinBane"));
  doc.setSubject("Dispute proof pack");
  doc.setCreator("CoinBane");
  doc.setProducer("CoinBane");

  doc.addPage([PAGE.width, PAGE.height]);
  drawCover(doc, fonts, pack);

  const writer = makeWriter(doc, doc.getPages()[1], fonts);

  /* Section 1 — the invoice, reproduced by the same code as the invoice PDF. */
  if (pack.invoice) {
    writer.ensure(120);
    sectionHeading(writer, 1, "Invoice details");
    const qr = pack.invoice.payUrl
      ? await doc.embedPng(await invoiceQrDataUrl(pack.invoice.payUrl))
      : null;
    /* The invoice header is positioned against the page, so it is shifted down
       to start where the section heading left the cursor. */
    drawInvoiceInto(writer, pack.invoice, qr, PAGE.height - 76 - writer.y);
  } else {
    sectionHeading(writer, 1, "Invoice details");
    drawParagraph(
      writer,
      "PayPal did not return an invoice for this dispute, and the ledger has no matching record. Attach the original invoice document yourself as supporting evidence.",
      { color: MUTED },
    );
    writer.y -= 10;
  }

  drawTimelineSection(writer, pack);
  drawPaymentsSection(writer, pack, fonts);
  drawPositionSection(writer, pack);
  drawEvidenceSection(writer, pack);

  drawFooters(doc, fonts, `Dispute proof pack \u00b7 ${pack.client}`);

  return doc.save();
}
