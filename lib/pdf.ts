import QRCode from "qrcode";

import { formatDay, shortPayUrl } from "./invoices.ts";
import type { DisputeProofPack, InvoicePayload } from "./types.ts";

/**
 * The documents CoinBane renders: one invoice, and the dispute proof pack that
 * bundles an invoice with the evidence around it.
 *
 * pdf-lib is used rather than pdfkit because it is the same code on the server
 * and in the browser: the API routes render it today, and nothing here would
 * have to change for a client-side export later.
 *
 * The two documents share one invoice layout — `drawInvoiceInto` — so the
 * reproduction in the proof pack cannot drift from the invoice the client was
 * actually sent. That is the whole point of section 1.
 *
 * The PayPal link is never invented. Where an invoice carries no hosted payer
 * view, the pay panel says so and drops the QR rather than printing a URL that
 * would not accept a payment.
 */

/** A4 portrait, the size a freelancer's client is most likely to print. */
const PAGE = { width: 595.28, height: 841.89 };
const MARGIN = 48;
/** Room kept at the foot of every page for the running footer. */
const FOOTER_BAND = 44;

const INK = rgb(0.04, 0.05, 0.07);
const MUTED = rgb(0.42, 0.45, 0.5);
const LINE = rgb(0.89, 0.9, 0.92);
const PANEL = rgb(0.96, 0.97, 0.98);
const PAYPAL = rgb(0, 0.439, 0.729);
const ACCENT = rgb(0.29, 0.61, 1);
const CYAN = rgb(0.39, 0.85, 1);
const WARNING = rgb(0.72, 0.36, 0.06);
const WHITE = rgb(1, 1, 1);

const FOOTER_LABEL = "Generated by CoinBane \u00b7 command every coin";

/**
 * WinAnsi cannot encode everything a client name might contain, and pdf-lib
 * throws rather than dropping a glyph. Map the punctuation that shows up in
 * real names and copy, and replace the rest.
 */
const PUNCTUATION: Record<string, string> = {
  "\u2018": "'",
  "\u2019": "'",
  "\u201c": '"',
  "\u201d": '"',
  "\u2013": "-",
  "\u2014": "-",
  "\u2026": "...",
  "\u00a0": " ",
  "\u00ad": "",
};

/** Strips anything the standard fonts cannot draw. */
export function pdfSafe(value: string): string {
  let out = "";
  for (const char of value) {
    const mapped = PUNCTUATION[char] ?? char;
    for (const glyph of mapped) {
      const code = glyph.codePointAt(0) ?? 0;
      if (code === 10 || code === 13) out += " ";
      else if (code >= 32 && code <= 255) out += glyph;
      else out += "?";
    }
  }
  return out;
}

/**
 * `$2,100.00` for dollars and `EUR 1,200.00` for everything else — the reading
 * a client expects on a printed invoice.
 */
export function formatPdfMoney(amount: number, currency: string): string {
  const value = amount.toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return currency.toUpperCase() === "USD" ? `$${value}` : `${currency} ${value}`;
}

/**
 * The QR an invoice PDF embeds, as a PNG data URL.
 *
 * Exported because it is the one piece worth testing on its own: a test can
 * decode this back to the URL and prove the code scans, which is not something
 * a rendered PDF can be asked.
 */
export async function invoiceQrDataUrl(url: string, width = 512): Promise<string> {
  return QRCode.toDataURL(url, {
    errorCorrectionLevel: "M",
    margin: 1,
    width,
    type: "image/png",
  });
}

/**
 * Truncates to fit a box, with an ellipsis when it does not.
 *
 * Measuring has to happen on the sanitised text: a glyph the font cannot
 * encode throws inside `widthOfTextAtSize`, which would take the whole request
 * down over one emoji in a line item.
 */
function fit(font: PDFFont, text: string, size: number, maxWidth: number): string {
  const safe = pdfSafe(text);
  if (font.widthOfTextAtSize(safe, size) <= maxWidth) return safe;
  let clipped = safe;
  while (clipped.length > 1 && font.widthOfTextAtSize(`${clipped}...`, size) > maxWidth) {
    clipped = clipped.slice(0, -1);
  }
  return `${clipped}...`;
}

/** Greedy word wrap. Measuring first is what lets a block know its own height. */
function wrapText(
  font: PDFFont,
  text: string,
  size: number,
  maxWidth: number,
): string[] {
  const words = pdfSafe(text).split(/\s+/).filter(Boolean);
  if (words.length === 0) return [""];

  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const candidate = current ? `${current} ${word}` : word;
    if (!current || font.widthOfTextAtSize(candidate, size) <= maxWidth) {
      current = candidate;
    } else {
      lines.push(current);
      current = word;
    }
  }
  lines.push(current);
  return lines;
}

function label(page: PDFPage, font: PDFFont, text: string, x: number, y: number) {
  page.drawText(pdfSafe(text.toUpperCase()), {
    x,
    y,
    size: 7.5,
    font,
    color: MUTED,
  });
}

function rightAlign(
  page: PDFPage,
  text: string,
  right: number,
  y: number,
  size: number,
  font: PDFFont,
  color = INK,
) {
  const safe = pdfSafe(text);
  page.drawText(safe, {
    x: right - font.widthOfTextAtSize(safe, size),
    y,
    size,
    font,
    color,
  });
}

function centerAlign(
  page: PDFPage,
  text: string,
  y: number,
  size: number,
  font: PDFFont,
  color = INK,
) {
  const safe = pdfSafe(text);
  page.drawText(safe, {
    x: PAGE.width / 2 - font.widthOfTextAtSize(safe, size) / 2,
    y,
    size,
    font,
    color,
  });
}

interface Fonts {
  regular: PDFFont;
  bold: PDFFont;
  italic: PDFFont;
}

/**
 * A page plus a cursor.
 *
 * Both documents paginate, but not identically: the invoice repeats its table
 * header on a continuation page and the pack does not. Folding that into
 * `newPage` keeps one copy of the invoice layout while letting each document
 * decide how it breaks.
 */
interface Writer {
  doc: PDFDocument;
  page: PDFPage;
  y: number;
  fonts: Fonts;
  newPage(then?: () => void): void;
  /** Breaks the page first when `space` would run into the footer. */
  ensure(space: number, then?: () => void): void;
}

function makeWriter(doc: PDFDocument, page: PDFPage, fonts: Fonts): Writer {
  const writer: Writer = {
    doc,
    page,
    y: PAGE.height - MARGIN,
    fonts,
    newPage(then) {
      writer.page = writer.doc.addPage([PAGE.width, PAGE.height]);
      writer.y = PAGE.height - MARGIN;
      then?.();
    },
    ensure(space, then) {
      if (writer.y - space < MARGIN + FOOTER_BAND) writer.newPage(then);
    },
  };
  return writer;
}

/** A wrapped paragraph, breaking pages line by line. */
function drawParagraph(
  writer: Writer,
  text: string,
  options: {
    size?: number;
    font?: PDFFont;
    color?: ReturnType<typeof rgb>;
    width?: number;
    x?: number;
    lineHeight?: number;
  } = {},
): void {
  const size = options.size ?? 9.5;
  const font = options.font ?? writer.fonts.regular;
  const x = options.x ?? MARGIN;
  const width = options.width ?? PAGE.width - MARGIN - x;
  const lineHeight = options.lineHeight ?? size * 1.35;

  for (const line of wrapText(font, text, size, width)) {
    writer.ensure(lineHeight, () => undefined);
    writer.page.drawText(line, {
      x,
      y: writer.y,
      size,
      font,
      color: options.color ?? INK,
    });
    writer.y -= lineHeight;
  }
}

/* ------------------------------------------------------------------ *
 * The invoice layout, shared by both documents
 * ------------------------------------------------------------------ */

/** The spreadsheet-style table column geometry, shared by header and rows. */
const COLUMNS = {
  left: MARGIN,
  right: PAGE.width - MARGIN,
  description: MARGIN + 10,
  quantityRight: MARGIN + 300,
  rateRight: MARGIN + 400,
  amountRight: PAGE.width - MARGIN - 10,
};

type EmbeddedPng = Awaited<ReturnType<PDFDocument["embedPng"]>>;

/**
 * Draws the invoice: header, parties, metadata, items, total, pay panel.
 *
 * Assumes the cursor sits at the top of a fresh page — the invoice header is
 * positioned against the page, not against the cursor — and leaves `writer.y`
 * after the pay panel. `qr` is passed in rather than embedded here so the
 * caller embeds it once for whichever document it is building.
 */
function drawInvoiceInto(
  writer: Writer,
  invoice: InvoicePayload,
  qr: EmbeddedPng | null,
  /** Pushes the whole invoice down, for use under a heading on a shared page. */
  topShift = 0,
): void {
  const { regular, bold, italic } = writer.fonts;
  const page = writer.page;
  const money = (amount: number) => formatPdfMoney(amount, invoice.currency);
  const headerY = PAGE.height - 76 - topShift;

  /* ---------------------------------------------------------------- header */

  page.drawText("CoinBane", { x: MARGIN, y: headerY, size: 22, font: bold, color: INK });
  page.drawText(pdfSafe("Command every coin."), {
    x: MARGIN,
    y: headerY - 16,
    size: 9.5,
    font: regular,
    color: MUTED,
  });
  rightAlign(page, "INVOICE", PAGE.width - MARGIN, headerY, 22, bold);

  writer.y = headerY - 40;
  page.drawText(
    pdfSafe(
      '"Beware of little expenses; a small leak will sink a great ship." - Benjamin Franklin',
    ),
    { x: MARGIN, y: writer.y, size: 9, font: italic, color: MUTED },
  );

  writer.y -= 16;
  page.drawLine({
    start: { x: MARGIN, y: writer.y },
    end: { x: PAGE.width - MARGIN, y: writer.y },
    thickness: 1,
    color: LINE,
  });

  /* ----------------------------------------------------------- two parties */

  writer.y -= 30;
  const leftColumn = MARGIN;
  const rightColumn = MARGIN + 270;
  const partyTop = writer.y;

  label(page, bold, "From", leftColumn, partyTop);
  page.drawText(pdfSafe(invoice.invoicer.business ?? invoice.invoicer.name), {
    x: leftColumn,
    y: partyTop - 18,
    size: 11,
    font: bold,
    color: INK,
  });
  let fromY = partyTop - 33;
  const fromLines = [
    invoice.invoicer.business && invoice.invoicer.name !== invoice.invoicer.business
      ? invoice.invoicer.name
      : null,
    ...invoice.invoicer.lines,
    invoice.invoicer.email,
  ].filter((line): line is string => Boolean(line));
  for (const line of fromLines) {
    page.drawText(pdfSafe(fit(regular, line, 9.5, 250)), {
      x: leftColumn,
      y: fromY,
      size: 9.5,
      font: regular,
      color: MUTED,
    });
    fromY -= 13;
  }

  label(page, bold, "Bill to", rightColumn, partyTop);
  page.drawText(pdfSafe(invoice.recipient.business ?? invoice.recipient.name), {
    x: rightColumn,
    y: partyTop - 18,
    size: 11,
    font: bold,
    color: INK,
  });
  let toY = partyTop - 33;
  const toLines = [
    invoice.recipient.business && invoice.recipient.name !== invoice.recipient.business
      ? invoice.recipient.name
      : null,
    ...invoice.recipient.lines,
    invoice.recipient.email,
  ].filter((line): line is string => Boolean(line));
  for (const line of toLines) {
    page.drawText(pdfSafe(fit(regular, line, 9.5, 250)), {
      x: rightColumn,
      y: toY,
      size: 9.5,
      font: regular,
      color: MUTED,
    });
    toY -= 13;
  }

  /* -------------------------------------------------------------- metadata */

  writer.y = Math.min(fromY, toY) - 12;
  const metaColumns = [
    { label: "Invoice number", value: invoice.number, x: MARGIN },
    { label: "Issued", value: invoice.issued ?? "Not recorded", x: MARGIN + 170 },
    {
      // PayPal's own fallback term is literally "no due date", so say that
      // rather than putting a made-up date next to a real one.
      label: "Due",
      value: invoice.due ?? "On receipt",
      x: MARGIN + 340,
    },
  ];
  for (const meta of metaColumns) {
    label(page, bold, meta.label, meta.x, writer.y);
    page.drawText(pdfSafe(fit(bold, meta.value, 10.5, 150)), {
      x: meta.x,
      y: writer.y - 15,
      size: 10.5,
      font: bold,
      color: INK,
    });
  }
  writer.y -= 40;

  /* ----------------------------------------------------------- items table */

  const drawTableHeader = () => {
    writer.page.drawRectangle({
      x: COLUMNS.left,
      y: writer.y - 6,
      width: COLUMNS.right - COLUMNS.left,
      height: 22,
      color: PANEL,
    });
    const baseline = writer.y + 1;
    label(writer.page, bold, "Description", COLUMNS.description, baseline);
    rightAlign(writer.page, "HOURS / QTY", COLUMNS.quantityRight, baseline, 7.5, bold, MUTED);
    rightAlign(writer.page, "RATE", COLUMNS.rateRight, baseline, 7.5, bold, MUTED);
    rightAlign(writer.page, "AMOUNT", COLUMNS.amountRight, baseline, 7.5, bold, MUTED);
    writer.y -= 26;
  };

  drawTableHeader();

  const rows = invoice.items.length
    ? invoice.items
    : [{ description: "Services rendered", quantity: 1, unit: null, unitAmount: invoice.total, amount: invoice.total }];

  for (const item of rows) {
    if (writer.y - 20 < MARGIN + 190) writer.newPage(drawTableHeader);

    const quantity = item.unit === "HOURS" ? `${item.quantity} hrs` : String(item.quantity);
    writer.page.drawText(pdfSafe(fit(regular, item.description, 9.5, 250)), {
      x: COLUMNS.description,
      y: writer.y,
      size: 9.5,
      font: regular,
      color: INK,
    });
    rightAlign(writer.page, quantity, COLUMNS.quantityRight, writer.y, 9.5, regular, MUTED);
    rightAlign(writer.page, money(item.unitAmount), COLUMNS.rateRight, writer.y, 9.5, regular, MUTED);
    rightAlign(writer.page, money(item.amount), COLUMNS.amountRight, writer.y, 9.5, regular, INK);

    writer.y -= 8;
    writer.page.drawLine({
      start: { x: COLUMNS.left, y: writer.y },
      end: { x: COLUMNS.right, y: writer.y },
      thickness: 0.5,
      color: LINE,
    });
    writer.y -= 14;
  }

  writer.y -= 4;
  writer.page.drawLine({
    start: { x: COLUMNS.rateRight - 40, y: writer.y },
    end: { x: COLUMNS.right, y: writer.y },
    thickness: 1,
    color: LINE,
  });
  writer.y -= 18;
  rightAlign(writer.page, "TOTAL", COLUMNS.rateRight, writer.y, 9, bold, MUTED);
  rightAlign(writer.page, money(invoice.total), COLUMNS.amountRight, writer.y, 13, bold, INK);
  writer.y -= 24;

  /* --------------------------------------------------------- pay with link */

  if (writer.y - 200 < MARGIN + FOOTER_BAND) writer.newPage();

  const panelTop = writer.y;
  const panelHeight = 180;
  writer.page.drawRectangle({
    x: COLUMNS.left,
    y: panelTop - panelHeight,
    width: COLUMNS.right - COLUMNS.left,
    height: panelHeight,
    color: PANEL,
    borderColor: LINE,
    borderWidth: 1,
  });

  writer.page.drawText("Pay Now with PayPal", {
    x: COLUMNS.left + 18,
    y: panelTop - 30,
    size: 13,
    font: bold,
    color: INK,
  });

  const buttonTop = panelTop - 58;
  const buttonWidth = 250;
  const buttonHeight = 42;
  const buttonX = COLUMNS.left + 18;

  if (invoice.payUrl && qr) {
    /* QR at the left of the panel, its typable short form directly beneath. */
    const qrSize = 104;
    const qrX = COLUMNS.left + 18;
    const qrY = panelTop - panelHeight + 22;
    writer.page.drawImage(qr, { x: qrX, y: qrY, width: qrSize, height: qrSize });

    const short = shortPayUrl(invoice.payUrl);
    const shortSize = 7.5;
    const shortText = fit(regular, short, shortSize, 170);
    writer.page.drawText(pdfSafe(shortText), {
      x: qrX + qrSize / 2 - regular.widthOfTextAtSize(pdfSafe(shortText), shortSize) / 2,
      y: qrY - 11,
      size: shortSize,
      font: regular,
      color: MUTED,
    });

    /* The pay button, to the right of the QR. */
    const payX = qrX + qrSize + 26;
    const payY = buttonTop - buttonHeight;
    writer.page.drawRectangle({
      x: payX,
      y: payY,
      width: buttonWidth,
      height: buttonHeight,
      color: PAYPAL,
    });
    const payText = pdfSafe(`Pay ${formatPdfMoney(invoice.total, invoice.currency)} via PayPal`);
    const paySize = 12;
    writer.page.drawText(fit(bold, payText, paySize, buttonWidth - 24), {
      x: payX + buttonWidth / 2 - bold.widthOfTextAtSize(fit(bold, payText, paySize, buttonWidth - 24), paySize) / 2,
      y: payY + buttonHeight / 2 - 4,
      size: paySize,
      font: bold,
      color: WHITE,
    });

    writer.page.drawText(pdfSafe("Scan the code or open the link to pay this invoice."), {
      x: payX,
      y: payY - 16,
      size: 8.5,
      font: regular,
      color: MUTED,
    });

    /* A hairline of brand colour so the panel does not read as a plain table. */
    writer.page.drawLine({
      start: { x: payX, y: payY - 28 },
      end: { x: payX + 60, y: payY - 28 },
      thickness: 2,
      color: ACCENT,
    });
    writer.page.drawLine({
      start: { x: payX + 66, y: payY - 28 },
      end: { x: payX + 96, y: payY - 28 },
      thickness: 2,
      color: CYAN,
    });
  } else {
    writer.page.drawText(
      pdfSafe(
        "No PayPal pay link on this invoice yet. Send it from PayPal to generate the page your client pays from.",
      ),
      {
        x: buttonX,
        y: buttonTop - 16,
        size: 10,
        font: regular,
        color: MUTED,
        maxWidth: COLUMNS.right - COLUMNS.left - 36,
        lineHeight: 14,
      },
    );
  }

  writer.y = panelTop - panelHeight - 24;
}

/** The running footer, on every page of whichever document was built. */
function drawFooters(doc: PDFDocument, fonts: Fonts, label = FOOTER_LABEL): void {
  const pages = doc.getPages();
  pages.forEach((current, index) => {
    const baseline = MARGIN - 14;
    current.drawLine({
      start: { x: MARGIN, y: baseline + 14 },
      end: { x: PAGE.width - MARGIN, y: baseline + 14 },
      thickness: 0.5,
      color: LINE,
    });
    current.drawText(pdfSafe(label), {
      x: MARGIN,
      y: baseline,
      size: 8.5,
      font: fonts.regular,
      color: MUTED,
    });
    if (pages.length > 1) {
      rightAlign(
        current,
        `Page ${index + 1} of ${pages.length}`,
        PAGE.width - MARGIN,
        baseline,
        8.5,
        fonts.regular,
        MUTED,
      );
    }
  });
}

async function embedFonts(doc: PDFDocument): Promise<Fonts> {
  return {
    regular: await doc.embedFont(StandardFonts.Helvetica),
    bold: await doc.embedFont(StandardFonts.HelveticaBold),
    italic: await doc.embedFont(StandardFonts.HelveticaOblique),
  };
}

/* ------------------------------------------------------------------ *
 * The invoice document
 * ------------------------------------------------------------------ */

export async function generateInvoicePdf(invoice: InvoicePayload): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(pdfSafe(`Invoice ${invoice.number} - ${invoice.client}`));
  doc.setAuthor(pdfSafe(invoice.invoicer.business ?? invoice.invoicer.name));
  doc.setSubject("Invoice");
  doc.setCreator("CoinBane");
  doc.setProducer("CoinBane");

  const fonts = await embedFonts(doc);
  const qr = invoice.payUrl
    ? await doc.embedPng(await invoiceQrDataUrl(invoice.payUrl))
    : null;

  const writer = makeWriter(doc, doc.addPage([PAGE.width, PAGE.height]), fonts);
  drawInvoiceInto(writer, invoice, qr);
  drawFooters(doc, fonts);

  return doc.save();
}

